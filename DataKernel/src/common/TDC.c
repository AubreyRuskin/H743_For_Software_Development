/* get the temperature using resistance value.
 * Para:
 *     rx, resistance value, magnified 100.
 *     option, type of resistance.
 * Return:
 *     temperature, magnified 256.
 */
INT16 GetTemperature(int32_t rx, uint8_t option)
{
    int16_t t1, t2, temp, result;
    const uint16_t *pt = NULL;
    static uint16_t nCurLoc = 0;	/* 该变量连续使用 */

    if (option == 0)
        pt = cu50;
    else if (option == 1)
        pt = cu100;
    else if (option == 2)
        pt = pt100ba2;
    else if (option == 3)
        pt = pt100;
    else if (option == 4)
        pt = cu53;


    if (rx<0)
        return -30*256;
    while (rx>pt[nCurLoc] && nCurLoc<nSize-1)
        nCurLoc++;
    while (rx<pt[nCurLoc] && nCurLoc>1)
        nCurLoc--;

    if (nCurLoc >= nSize-1)
        return 120*256;		/* 30720; */
    else if (nCurLoc <= 1)
        return -30*256;	/* -7680; */
    else
    {
        t1 = pt[nCurLoc];
        t2 = pt[nCurLoc+1];
        result = nCurLoc-30;
        result <<= 8;
        temp = t2-t1;
        result += (((rx-t1)<<8)+(temp>>1))/temp;

        return result;
    }
}
